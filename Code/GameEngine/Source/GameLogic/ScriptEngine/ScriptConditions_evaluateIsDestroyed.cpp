Bool ScriptConditions::evaluateIsDestroyed(Parameter *pTeamParm)
{
	Team *theTeam = TheScriptEngine->getTeamNamed(pTeamParm->getString(), false);
	if (theTeam) {
		if (!theTeam->isReady()) {
			return false;
		}
		return (!theTeam->hasAnyObjects(false));
	}
	return false;
}
