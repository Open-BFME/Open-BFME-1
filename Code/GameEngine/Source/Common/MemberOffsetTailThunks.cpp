// A hundred and eighty-eight tiny __thiscall members that hand control to a
// __thiscall member of a sub-object held at a fixed offset inside the class:
//
//     add ecx,<OFFSET> / jmp <REL32>
//
// WHAT THE BYTES SHOW.  `this` arrives in ecx, a constant is added to it, and
// control leaves through a jmp, so the callee inherits this frame unchanged and
// its `ret` returns to OUR caller.  The bare jmp preserves any stack arguments
// from this function's caller; the callee's `ret` decides their cleanup.  A
// signature therefore needs independent evidence for each target.  In
// particular, 0x00594000 forwards one pointer-sized argument and its callee
// 0x00593A30 ends in `ret 4`.  The added constant is the offset of the
// receiver inside the object.
//
// TWO AXES, AND NEITHER IS INFERRED: the offset is an immediate operand and the
// target is the displacement, so both are read straight off the instruction
// pair rather than fitted.  A hundred and eighty-eight members over ninety-one
// callees at forty-one distinct offsets.  Two callees carry most of the
// fan-in -- one reached by fifty members and one by twenty-six -- which is why
// members outnumber callees.  Members that share BOTH a callee and an offset
// are separate functions that compile to the same nine bytes, not aliases: each
// occupies its own address in the image, and a fold would have left one.
//
// Five of the offsets are NEGATIVE -- three at -32, one at -16 and one at -228.
// The compiler spells a subtraction of a constant from ecx as an addition of
// its negation, so those bodies read `add ecx,-N`, and the receiver sits BEFORE
// the object rather than inside it.  That is why the receiver is reached by
// pointer arithmetic here instead of being declared as a member: a member at a
// negative offset cannot be spelled, and using one spelling for all hundred and
// eighty-eight keeps the family a single shape.
//
// IDENTITY IS NOT RECOVERED.  Every name is derived from an address; the callee
// pins are address-derived and additive.

