class BfmeThingCA
{
public:
	void bfmeGoCA(int what);

private:
	unsigned char m_bfmeHead[0x30];		// 0x00
	BfmeOwnerCA *m_bfmeOwner;		// 0x30
	unsigned char m_bfmeGap[0x14];		// 0x34
	int m_bfmeWhat;				// 0x48
};

void BfmeThingCA::bfmeGoCA(int what)
{
	BfmeOwnerCA *owner = m_bfmeOwner;
	BfmeTargetCA *target = owner->m_bfmeTarget;

	if (target != 0 && target->m_bfmeKind == 0x2d)
		return;

	owner->bfmeStopCA();

	m_bfmeWhat = what;

	m_bfmeOwner->bfmeStartCA(0x2d);
}
