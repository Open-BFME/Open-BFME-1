// Two hundred and ninety-three compiler-generated ADJUSTOR THUNKS.  Each is a
// virtual-call entry that steps `this` back from a secondary base sub-object to
// the most-derived object and jumps to the real override:
//
//     sub ecx,<OFFSET> / jmp <REL32>
//
// WHAT THE BYTES SHOW.  ecx is decreased by a constant and control leaves
// through a jmp, so the callee inherits this frame and its `ret` returns to the
// virtual call site.  A DECREASE is the tell.  Ordinary pointer arithmetic
// written in source compiles to `add ecx,-N` -- the compiler spells a constant
// subtraction as an addition of its negation -- so `sub ecx,N` is not something
// hand-written code produces here.  The one construct that emits it is the
// thunk MSVC synthesises when a single override has to serve the vtable slot of
// a base that does not sit at offset zero: the slot is entered with a pointer
// to that base, and the override expects the most-derived pointer.
//
// THESE ARE THEREFORE NOT HAND-WRITTEN FUNCTIONS AT ALL, and they are declared
// the only way that reproduces them -- by declaring the inheritance that makes
// the compiler emit them.  Each row below builds a most-derived class over two
// polymorphic bases, the first sized so that the second lands at the offset the
// thunk subtracts, with ONE virtual function overridden for both.  The override
// itself is only DECLARED: it lives at the address the REL32 names and is
// pinned there, so the thunk in this translation unit is the claimed body and
// the override is an external.
//
// TWO AXES, BOTH READ DIRECTLY: the subtracted offset and the REL32 target.
// Eighteen distinct offsets from 4 to 832 bytes; offsets of 128 and above use
// the 32-bit immediate form and make the thunk eleven bytes instead of eight.
//
// GROUPING BY BYTES SEES THIS AS EIGHTEEN SEPARATE FAMILIES, one per offset, and
// a six-member threshold drops TEN of them -- sixteen rows at the offsets 20,
// 36, 60, 88, 96, 112, 180, 252, 600 and 832 bytes.  Sweeping the shape as a
// pattern with the offset wildcarded is what collected all two hundred and
// ninety-three.
//
// IDENTITY IS NOT RECOVERED.  Every class name is derived from the thunk's own
// address; the override pins are address-derived and additive.

#define BFME_ADJUSTOR_THUNK( NAME, OFFSET )                               \
	class NAME##Lead                                                      \
	{                                                                     \
	public:                                                               \
		virtual void handle();                                            \
		char m_fill[ ( OFFSET ) - 4 ];                                    \
	};                                                                    \
	class NAME##Alternate                                                 \
	{                                                                     \
	public:                                                               \
		virtual void handle();                                            \
	};                                                                    \
	class NAME : public NAME##Lead, public NAME##Alternate                \
	{                                                                     \
	public:                                                               \
		NAME();                                                           \
		virtual void handle();                                            \
	};                                                                    \
	NAME::NAME()                                                          \
	{                                                                     \
	}

