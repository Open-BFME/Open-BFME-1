// 217 __cdecl free functions that walk an array and hand each slot to one
// direct call.  Two loop shapes over 20 element strides:
//
//     45 bytes -- bounded by an end pointer, one call per slot, two cursors:
//         f(first,last,dest): while (first!=last) callee(dest,first), both += S
//     41 bytes -- bounded by a count, one call per slot, one cursor:
//         f(first,n,value):   while (n>0) callee(first,value), first += S, --n
//
// Both return the ADVANCED cursor, not the incoming pointer.
//
// THE FAMILY IS INVISIBLE TO BYTE-IDENTITY GROUPING.  The one call in each body
// is a REL32, so a call to a fixed callee encodes a different four-byte
// displacement from every address; masking that displacement before hashing is
// what found these at all.
//
// WHAT THE BYTES SHOW.  Arguments are read at [esp+4] upward, ecx is untouched
// and the `add esp,8` after each call is the caller's own cleanup: __cdecl
// throughout, and the callee takes two dwords.  The stride is the constant
// added to the cursor each turn, and it is the ONLY thing that differs between
// one member and the next apart from the call target -- which is why every
// stride lives in this one file.  The count is tested with `test/jbe`, an
// UNSIGNED `> 0`; a signed `!= 0` compiles to `je` and does not match.
//
// ONE SHAPE FINDING, read off a failing diff rather than guessed.  Writing the
// loop over the PARAMETER gives the compiler a second return path that reloads
// that parameter from the stack (52 and 47 bytes); copying it into a local
// cursor first, so the returned value lives in one register on both paths,
// collapses that to the retail 45 and 41.  The bytes settle that distinction.
//
// THE STRIDES AND THE CALLEES AGREE.  Every callee reached by a body of one
// stride is reached only by bodies of that same stride -- checked over all
// 96 of them, with no exception -- and the two loop shapes SHARE
// callees within a stride.  A copying walk and a filling walk over the same
// element type calling the same two-argument helper is exactly that pattern, so
// a shared callee carries ONE name and ONE pin rather than one per shape.
//
// IDENTITY IS NOT RECOVERED.  The element types are stand-ins sized to the
// stride the bytes prove and nothing more; names are address-derived and the
// callee pins are additive and address-derived.

#define BFME_ELEMENT_TYPE( TYPE, SIZE )                                      \
	struct TYPE { char m_bytes[ SIZE ]; };

#define BFME_ELEMENT_CALLEE( TYPE, ADDR )                                    \
	void gen##ADDR( TYPE *slot, const TYPE *source );

#define BFME_ELEMENT_COPY_WALK( TYPE, NAME, CALLEE )                         \
	TYPE *NAME( TYPE *first, TYPE *last, TYPE *dest )                        \
	{                                                                        \
		TYPE *cursor = dest;                                                 \
		for ( ; first != last; ++first )                                     \
		{                                                                    \
			CALLEE( cursor, first );                                         \
			++cursor;                                                        \
		}                                                                    \
		return cursor;                                                       \
	}

#define BFME_ELEMENT_FILL_WALK( TYPE, NAME, CALLEE )                         \
	TYPE *NAME( TYPE *first, unsigned int count, const TYPE *value )         \
	{                                                                        \
		TYPE *cursor = first;                                                \
		for ( ; count > 0; --count )                                         \
		{                                                                    \
			CALLEE( cursor, value );                                         \
			++cursor;                                                        \
		}                                                                    \
		return cursor;                                                       \
	}

