// Seventy-three 33-byte __stdcall free functions that ask one allocator for a
// fixed number of bytes, hand a fixed offset into the block to one initialiser
// together with their own argument, and return the block:
//
//     push esi / push <SIZE> / call <ALLOCATOR> / mov esi,eax
//     mov eax,[esp+0xC] / push eax / lea ecx,[esi+<OFFSET>] / push ecx
//     call <INITIALISER> / add esp,0xC / mov eax,esi / pop esi / ret 4
//
// WHAT THE BYTES SHOW.  `ret 4` with one dword read and ecx never used as an
// object is __stdcall with one argument; [esp+0xC] is that argument seen past
// the saved esi and the pushed size.  ONE `add esp,0xC` retires THREE pushed
// dwords -- the allocator's one and the initialiser's two -- so both callees
// are __cdecl and the compiler merged their cleanups; an allocator that popped
// its own argument would have left `add esp,8` here.  The allocation result is
// used without a null check, and `mov eax,esi` returns the block itself rather
// than the offset interior pointer handed to the initialiser.
//
// THREE AXES, ALL READ DIRECTLY OFF THE INSTRUCTIONS: the requested size (an
// immediate), the interior offset (an immediate), and the two REL32 targets.
// Twenty-one distinct sizes from 12 to 824 bytes, two offsets (8 and 16), two
// allocators and seventy-one initialisers.
//
// GROUPING BY BYTES WOULD HAVE FOUND A QUARTER OF THIS.  Members differing only
// in the size immediate are not byte-identical, so most of them sit alone in
// their own group; sweeping the shape as a PATTERN with the immediates
// wildcarded is what collected all seventy-three.
//
// IDENTITY IS NOT RECOVERED.  Every name is derived from an address; the callee
// pins are address-derived and additive.

#define BFME_BLOCK_ALLOCATOR( ADDR )                                      \
	void *gen##ADDR( unsigned int size );                                 \

#define BFME_BLOCK_INITIALISER( ADDR )                                    \
	void gen##ADDR( void *storage, void *argument );                      \

#define BFME_ALLOCATE_THEN_INITIALISE( NAME, ALLOC, INIT, SIZE, OFFSET )  \
	void * __stdcall NAME( void *argument )                               \
	{                                                                     \
		void *block = ALLOC( SIZE );                                      \
		INIT( (char *)block + ( OFFSET ), argument );                     \
		return block;                                                     \
	}

