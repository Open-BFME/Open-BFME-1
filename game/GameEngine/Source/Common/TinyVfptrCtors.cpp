// One hundred and forty-six 9-byte __thiscall bodies of the single shape
//
//     mov eax,ecx / mov dword ptr [eax],<DIR32> / ret
//
// WHAT THE BYTES SHOW.  `this` is copied to eax and returned, and a relocated
// absolute address is stored at offset 0 of the object: that is a CONSTRUCTOR
// of a polymorphic class installing its vfptr, with no base ctor call, no
// member initialisation and no argument.  MSVC 7.1 emits exactly these nine
// bytes for `C::C() {}` on a class whose only stored state is the vfptr.
//
// ONE AXIS: the vftable address.  It rides a DIR32 relocation, and the gate
// takes a DIR32 site's four bytes from retail, so the address each ctor stores
// is not evidence and is not reconstructed here -- what these rows prove is the
// SHAPE (copy this, store one relocated dword, return this), together with the
// fact that all 146 addresses are distinct.
//
// IDENTITY IS NOT RECOVERED.  Every class name is derived from the retail RVA
// of its constructor; the virtual member is declared and never defined, which
// is all the vftable emission needs.

#define BFME_VFPTR_CTOR( NAME )                                           \
	class NAME                                                             \
	{                                                                      \
	public:                                                                \
		NAME();                                                             \
		virtual void slot();                                                \
	};                                                                     \
	NAME::NAME()                                                           \
	{                                                                      \
	}

