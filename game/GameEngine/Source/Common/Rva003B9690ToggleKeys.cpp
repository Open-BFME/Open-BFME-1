void Rva003B9690::toggleKeys(const AsciiString &suffix, bool enable)
{
	for (unsigned int i = 0; i < m_items.size(); ++i)
	{
		if (m_items[i].m_owner != 0)
		{
			int key;
			Rva003B9690Ref *ref = m_items[i].m_owner->lookup(
				(m_items[i].m_name + "." + suffix).str(), &key);
			if (ref != 0)
			{
				ref->slot100(!enable);
				if (--ref->m_references == 0)
					ref->release();
				_STL::set<int>::iterator it = m_items[i].m_keys.find(key);
				if (enable)
				{
					if (it == m_items[i].m_keys.end())
						m_items[i].m_keys.insert(key);
				}
				else if (it != m_items[i].m_keys.end())
				{
					m_items[i].m_keys.erase(it);
				}
			}
		}
	}
}
