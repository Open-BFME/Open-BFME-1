// A hundred and seventy-nine 9-byte __cdecl free functions, each of which
// hands its one pointer argument to a __thiscall member and tail-jumps there:
//
//     mov ecx,[esp+4] / jmp <REL32>
//
// WHAT THE BYTES SHOW.  The argument at [esp+4] is loaded into ecx and control
// leaves through a jmp, so the callee inherits this frame unchanged and its own
// `ret` returns to OUR caller.  A jmp and no ret means the callee's stack pop
// is this function's stack pop: the callee ends in a bare `ret`, so it is
// __thiscall with no stack arguments, and the caller therefore pops the one
// dword itself -- __cdecl with one pointer argument.
//
// ARITY IS NOT DECIDABLE HERE.  A forwarder that also passed further arguments
// through would emit these same two instructions, because the extra dwords are
// already in place at [esp+8] upward.  The no-argument spelling is the one that
// asserts less, so it is the one written.
//
// THE ONLY AXIS IS THE REL32 TARGET: a hundred and seventy-nine members over a
// hundred and seventy-nine distinct callees, one each.  Two members sharing a
// callee would have compiled to the same nine bytes; none does.
//
// IDENTITY IS NOT RECOVERED.  Every name is derived from an address and asserts
// nothing; the callee pins are likewise address-derived and additive.

#define BFME_TAIL_CALL_CALLEE( ADDR )                                     \
	class Gen##ADDR                                                       \
	{                                                                     \
	public:                                                               \
		void handle();                                                    \
	};

#define BFME_TAIL_CALL_BY_POINTER( NAME, CALLEE )                         \
	void NAME( CALLEE *object )                                           \
	{                                                                     \
		object->handle();                                                 \
	}

