// 102 identical 17-byte __cdecl forwarders:
//
//     mov ecx,[esp+4] / push 0 / push <DIR32> / call 0x00850920 / ret
//
// WHAT THE BYTES SHOW.  The receiver arrives as an ordinary STACK argument and
// is moved into ecx for the call, so this function is __cdecl and the callee is
// __thiscall.  Nothing is popped here and the frame is untouched, so the callee
// clears its own two stack arguments (its body at 0x00850920 ends in `ret 8`).
// Pushes go right-to-left, so the DIR32 is argument one and the literal 0 is
// argument two.  0x00850920 appends the pair to two parallel 16-entry arrays
// held at +0x00 and +0x40 of the receiver, counted by the dword at +0x80.
//
// ONE AXIS: the DIR32 operand.  All 102 are distinct addresses in .rdata, each
// the head of a 16-byte-record table; the callee address and the literal 0 are
// the same in every member.  Each table therefore gets its own extern here, so
// the gate's DIR32 consistency check sees one symbol per address.
//
// IDENTITY IS NOT RECOVERED.  Every name is derived from an address.

class Gen00850920
{
public:
	void handle( const void *table, int flags );
};

