unsigned int ParseAlphaNumericBitMask(const char *description, unsigned int fallback)
{
	if (description == 0) {
		return fallback;
	}

	unsigned int mask = 0;
	int bit;
	for (; (bit = GenCharToBit0012A430[*description]) >= 0; ++description) {
		mask |= 1U << bit;
	}

	return mask;
}
